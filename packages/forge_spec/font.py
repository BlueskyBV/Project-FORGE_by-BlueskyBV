def missing_letters(text: str) -> list[str]:
    """The letters of ``text`` the font doesn't have, each once, in order."""
    return list(dict.fromkeys(ch for ch in text if ch not in ADVANCES))


def text_width(text: str, height: float) -> float:
    """How long a line of ``text`` is, its capitals ``height`` tall: its letters' advances added up.

    >>> round(text_width("H", 10.0), 3)
    11.48
    """
    return sum(ADVANCES[ch] for ch in text) * height / CAP_HEIGHT
