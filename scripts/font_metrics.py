"""Write forge_spec/font.py: the pinned font's metrics, read from the font file.

Text's size and place are worked out from these (docs/definitions/text.md):
a capital is as tall as the letter H, and a line is as long as its letters'
advance widths added up, with no kerning. The spec layer stays free of
fontTools by reading the table this writes; tests/test_v2_font.py checks the
table against the font file.

    python scripts/font_metrics.py   # rewrite packages/forge_spec/font.py, then ruff format it
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "packages" / "forge_fonts" / "fonts" / "DejaVuSans-Bold.ttf"
OUT = ROOT / "packages" / "forge_spec" / "font.py"

#: The letters Forge writes: printable ASCII and Latin-1, and a few signs
#: briefs use (dashes, quotes, the diameter sign, arrows, comparisons).
LETTERS = (
    [chr(c) for c in range(0x20, 0x7F)]
    + [chr(c) for c in range(0xA0, 0x100)]
    + [chr(c) for c in (0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x20AC, 0x2122, 0x2264,
                        0x2265, 0x2300, 0x2116, 0x2190, 0x2192, 0x2191, 0x2193, 0x221E, 0x2248, 0x2260)]
)  # fmt: skip


def metrics() -> tuple[str, str, int, int, dict[str, int]]:
    """The font's name, version, units per em, the letter H's height, and each letter's advance."""
    from fontTools.pens.boundsPen import BoundsPen
    from fontTools.ttLib import TTFont

    font = TTFont(str(FONT))
    names = font["name"]
    name = str(names.getDebugName(4))
    version = str(names.getDebugName(5)).removeprefix("Version ").strip()
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    pen = BoundsPen(glyphs)
    glyphs[cmap[ord("H")]].draw(pen)
    assert pen.bounds is not None
    cap = round(pen.bounds[3] - pen.bounds[1])
    hmtx = font["hmtx"]
    advances = {letter: int(hmtx[cmap[ord(letter)]][0]) for letter in LETTERS}
    return name, version, int(font["head"].unitsPerEm), cap, advances


def source() -> str:
    name, version, upm, cap, advances = metrics()
    digest = hashlib.sha256(FONT.read_bytes()).hexdigest()
    rows = "\n".join(
        f"    {letter!a}: {advance}," for letter, advance in advances.items()
    )
    return f'''"""The pinned font's metrics: what text's size and place are worked out from.

Generated by scripts/font_metrics.py from packages/forge_fonts/fonts/{FONT.name};
don't edit it by hand. A capital is as tall as the letter H, and a line of
letters is as long as their advance widths added up, with no kerning
(docs/definitions/text.md).
"""

from __future__ import annotations

from collections.abc import Mapping

__all__ = ["CAP_HEIGHT", "FILE", "FONT", "SHA256", "UNITS_PER_EM", "VERSION", "missing_letters", "text_width"]

FONT = {name!r}
VERSION = {version!r}
FILE = {FONT.name!r}
SHA256 = {digest!r}
UNITS_PER_EM = {upm}
#: The letter H's height, in font units: a capital's height.
CAP_HEIGHT = {cap}
#: Each letter's advance width, in font units.
ADVANCES: Mapping[str, int] = {{
{rows}
}}


def missing_letters(text: str) -> list[str]:
    """The letters of ``text`` the font doesn't have, each once, in order."""
    return list(dict.fromkeys(ch for ch in text if ch not in ADVANCES))


def text_width(text: str, height: float) -> float:
    """How long a line of ``text`` is, its capitals ``height`` tall: its letters' advances added up.

    >>> round(text_width("H", 10.0), 3)
    11.48
    """
    return sum(ADVANCES[ch] for ch in text) * height / CAP_HEIGHT
'''


def main() -> int:
    OUT.write_text(source(), encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
