"""Write forge_spec/glyphs.py: the pinned font's letters, as the font file draws them.

A letter is its glyph's outline (docs/definitions/text.md): its contours, each
a closed run of points on the curve and quadratic B-spline control points
between them (TrueType's own curves), in font units. A composite glyph (an
accented letter) is decomposed into its components' contours, placed as the
font places them. Overlapping contours and contours nested in others are
kept as drawn: the letter is the region of nonzero winding. The spec layer,
the judge and the build read the table this writes, so none of them needs
fontTools; tests/test_v2_glyphs.py checks the table against the font file.

    python scripts/font_glyphs.py   # rewrite packages/forge_spec/glyphs.py (formatted as written)
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from font_metrics import FONT, LETTERS

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "packages" / "forge_spec" / "glyphs.py"

Contour = tuple[tuple[int, int, int], ...]


def contours() -> dict[str, tuple[Contour, ...]]:
    """Each letter's contours: each point (x, y, 1 on the curve or 0 a control point), in font units."""
    from fontTools.ttLib import TTFont

    font = TTFont(str(FONT))
    glyf = font["glyf"]
    cmap = font.getBestCmap()
    found: dict[str, tuple[Contour, ...]] = {}
    for letter in LETTERS:
        glyph = glyf[cmap[ord(letter)]]
        coordinates, ends, flags = glyph.getCoordinates(glyf)
        drawn: list[Contour] = []
        start = 0
        for end in ends:
            points = []
            for k in range(start, end + 1):
                x, y = coordinates[k]
                if x != int(x) or y != int(y):
                    raise ValueError(
                        f"{letter!r}: a point off the font's grid, ({x}, {y})"
                    )
                points.append((int(x), int(y), int(flags[k] & 1)))
            drawn.append(tuple(points))
            start = end + 1
        found[letter] = tuple(drawn)
    return found


def source() -> str:
    digest = hashlib.sha256(FONT.read_bytes()).hexdigest()
    rows = "\n".join(
        f"    {letter!a}: {drawn!r}," for letter, drawn in contours().items()
    )
    return f'''"""The pinned font's letters: their outlines, as the font file draws them.

Generated by scripts/font_glyphs.py from packages/forge_fonts/fonts/{FONT.name};
don't edit it by hand. Each letter is its glyph's contours in font units, each
a closed run of points ``(x, y, on)``: on the curve (``on`` 1), or a quadratic
B-spline's control point (``on`` 0) between two points on it; two control
points in a row have the curve's point midway between them, and a contour of
control points alone is all such midpoints (TrueType's curves). A composite
glyph is its components' contours, placed as the font places them.
Overlapping contours and contours nested in others are kept as drawn: a
letter is the region of nonzero winding (docs/definitions/text.md). Its
size, advance and place come from forge_spec.font.
"""

from __future__ import annotations

from collections.abc import Mapping

__all__ = ["CONTOURS", "SHA256"]

#: The font file's SHA-256, as forge_spec.font pins it.
SHA256 = "{digest}"
#: Each letter's contours, one letter a line.
# fmt: off
CONTOURS: Mapping[str, tuple[tuple[tuple[int, int, int], ...], ...]] = {{
{rows}
}}
# fmt: on
'''


def main() -> int:
    OUT.write_text(source(), encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
